"""Реестр лицензий (единый реестр учёта лицензий ФНС и реестры лицензирующих органов).

Банку запрещено принимать на обслуживание того, кто ведёт деятельность без обязательной
лицензии (ст. 7 п. 15 115-ФЗ). Мок выдаёт действующую лицензию каждой компании, чей основной
вид деятельности лицензируется, кроме компаний из `UNLICENSED`. Записи синтетические.
"""

from __future__ import annotations

from datetime import date, timedelta

from app.data import Company

# Лицензируемые виды деятельности по ОКВЭД (префикс кода): что написано в лицензии.
LICENSED_OKVED: dict[str, str] = {
    "11.01": "Производство и оборот этилового спирта и алкогольной продукции",
    "11.02": "Производство и оборот этилового спирта и алкогольной продукции",
    "11.03": "Производство и оборот этилового спирта и алкогольной продукции",
    "11.04": "Производство и оборот этилового спирта и алкогольной продукции",
    "21.20": "Производство лекарственных средств",
    "38.12": "Сбор, транспортирование, обработка отходов I–IV классов опасности",
    "38.22": "Сбор, транспортирование, обработка отходов I–IV классов опасности",
    "46.46": "Фармацевтическая деятельность",
    "47.73": "Фармацевтическая деятельность",
    "65": "Страховая деятельность",
    "80.10": "Частная охранная деятельность",
    "85.1": "Образовательная деятельность",
    "85.2": "Образовательная деятельность",
    "86": "Медицинская деятельность",
    "92.1": "Организация и проведение азартных игр",
}
# Лицензии нет, хотя основной вид деятельности её требует.
UNLICENSED: frozenset[str] = frozenset({"7707115143"})


def _activity(okved: str) -> tuple[str, str] | None:
    matches = [prefix for prefix in LICENSED_OKVED if okved.startswith(prefix)]
    if not matches:
        return None
    prefix = max(matches, key=len)
    return prefix, LICENSED_OKVED[prefix]


def licenses_response(company: Company) -> dict:
    licenses = []
    activity = _activity(company.okved)
    if activity is not None and company.inn not in UNLICENSED:
        issued = date.today() - timedelta(days=min(company.reg_days_ago, 730))
        licenses.append(
            {
                "Номер": f"Л{company.inn[-6:]}-{activity[0].replace('.', '')}",
                "ВидДеятельности": activity[1],
                "ОКВЭД": company.okved,
                "Статус": "ДЕЙСТВУЕТ",
                "ДатаВыдачи": issued.isoformat(),
            }
        )
    return {"ИНН": company.inn, "Лицензии": licenses}
