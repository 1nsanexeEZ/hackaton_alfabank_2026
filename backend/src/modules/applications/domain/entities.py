"""Entities inside the CreditApplication aggregate: changed only through it."""

from dataclasses import dataclass
from datetime import datetime
from uuid import UUID

from src.core.exceptions.exceptions import ConflictError, ValidationError
from src.modules.applications.domain.enums import DocumentStatus, InfoRequestStatus

MAX_DOCUMENT_SIZE = 20 * 1024 * 1024
DEFAULT_CONTENT_TYPES: frozenset[str] = frozenset({"application/pdf", "image/jpeg", "image/png"})
# Statements are parsed for the cash flow forecast, so only CSV
# (Windows browsers send .csv as application/vnd.ms-excel).
CONTENT_TYPES_BY_DOCUMENT: dict[str, frozenset[str]] = {
    "bank_statement": frozenset({"text/csv", "application/vnd.ms-excel"}),
}
# Documents a client may always attach, besides those the product requires.
OPTIONAL_DOCUMENT_TYPES: frozenset[str] = frozenset(
    {"bank_statement", "financial_statement", "other"}
)
MAX_FILENAME_LENGTH = 255


def allowed_content_types(document_type: str) -> frozenset[str]:
    return CONTENT_TYPES_BY_DOCUMENT.get(document_type, DEFAULT_CONTENT_TYPES)


@dataclass(slots=True)
class Document:
    id: UUID
    type: str
    filename: str
    content_type: str
    size_bytes: int
    # Generated by the server, the client's filename never becomes part of it.
    s3_key: str
    status: DocumentStatus
    uploaded_by: UUID
    created_at: datetime
    uploaded_at: datetime | None = None
    info_request_id: UUID | None = None
    review_comment: str | None = None

    @staticmethod
    def validate_upload(document_type: str, filename: str, content_type: str, size: int) -> None:
        if content_type not in allowed_content_types(document_type):
            raise ValidationError(
                "This file type is not accepted",
                details={
                    "field": "content_type",
                    "code": "content_type_not_allowed",
                    "allowed": sorted(allowed_content_types(document_type)),
                },
            )
        if not 0 < size <= MAX_DOCUMENT_SIZE:
            raise ValidationError(
                "File is empty or too large",
                details={"field": "size_bytes", "code": "bad_size", "max": MAX_DOCUMENT_SIZE},
            )
        if not filename.strip() or len(filename) > MAX_FILENAME_LENGTH:
            raise ValidationError(
                "Invalid file name", details={"field": "filename", "code": "invalid"}
            )

    @property
    def is_uploaded(self) -> bool:
        return self.status in (DocumentStatus.UPLOADED, DocumentStatus.ACCEPTED)

    def confirm_upload(self, actual_size: int, actual_content_type: str, now: datetime) -> None:
        """The object in storage must be what was announced."""
        if self.status is not DocumentStatus.PENDING_UPLOAD:
            raise ConflictError("Document is already confirmed", details={"code": "confirmed"})
        if actual_size != self.size_bytes or actual_content_type != self.content_type:
            raise ValidationError(
                "Uploaded file does not match the announced one",
                details={"code": "upload_mismatch"},
            )
        self.status = DocumentStatus.UPLOADED
        self.uploaded_at = now


@dataclass(slots=True)
class InfoRequest:
    id: UUID
    requested_fields: tuple[str, ...]
    requested_documents: tuple[str, ...]
    comment: str
    created_at: datetime
    due_at: datetime | None
    status: InfoRequestStatus = InfoRequestStatus.OPEN
    answered_at: datetime | None = None
    answered_by: UUID | None = None

    @property
    def is_open(self) -> bool:
        return self.status is InfoRequestStatus.OPEN

    def allows_field(self, name: str) -> bool:
        """`request`, `collateral`, `consents`, `beneficiary`, `beneficial_owners`,
        `product_fields` open a whole section; any other name is a single product field."""
        return name in self.requested_fields

    def answer(self, account_id: UUID, now: datetime) -> None:
        self.status = InfoRequestStatus.ANSWERED
        self.answered_at = now
        self.answered_by = account_id
