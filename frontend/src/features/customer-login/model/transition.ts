import type { LetterSnapshot } from '@/shared/ui'

/** Куда ведёт вход: на страницу профиля или сразу в мастер заявки (клиент нажимал «Оформить заявку») */
export type AfterLogin = 'profile' | 'application'

/** Как закрыть панель входа — см. `exit` в BaseDrawer */
export type DrawerExit = 'close' | 'handoff' | 'handoff-dark'

/** Что анимации нужно от панели входа: она сама решает только, когда это вызвать */
export interface LoginTransitionPlan {
  next: AfterLogin
  /** Где сейчас буквы фона: снимок берётся в тот кадр, когда их забирает анимация */
  letters: () => LetterSnapshot[]
  close: (exit: DrawerExit) => void
  /** Перейти на профиль; раскрытие ждёт, пока он отрисуется */
  navigate: () => Promise<unknown>
  /** Вход завершён: профиль открыт или пора открывать мастер заявки */
  done: () => void
}

/**
 * Тайминг «сборки в знак», мс. Вход на профиль — около 1,5 с, вход перед заявкой — 1,6 с до мастера;
 * подсветка логотипа идёт дальше сама и ничему не мешает.
 */
export const TIMING = {
  /** Галочка на кнопке, потом панель уходит */
  confirm: 200,
  /** Буквы долетают до точек знака, знак «впечатывается» */
  gather: 620,
  /** С этого момента своя тёмная подложка: затемнение панели вот-вот исчезнет вместе с ней */
  cover: 520,
  /** Знак заливает экран, под ним уже профиль */
  flood: 280,
  /** Профиль раскрывается кругом из центра, белая «А» летит в логотип */
  open: 420,
  /** Перед заявкой: знак сам улетает в логотип */
  fly: 440,
  /** Логотип подсвечен, потом открывается мастер заявки */
  wizardDelay: 300,
  /** Подсветка логотипа целиком */
  glow: 1400,
} as const
