/**
 * Буква декоративного слоя в момент снимка, в координатах окна: где её центр и как она выглядит.
 * По снимку анимация входа ставит на те же места свои копии букв и уводит их дальше сама.
 */
export interface LetterSnapshot {
  /** Центр буквы, px от левого верхнего угла окна */
  x: number
  y: number
  /** Видимый кегль, px: на широком экране — с поправкой на глубину сцены */
  size: number
  /** Наклон, градусы */
  rotate: number
  color: string
  shadow: string
  opacity: number
  filter: string
}
